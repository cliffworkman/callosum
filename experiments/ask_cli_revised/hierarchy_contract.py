def rollup(contract: dict, obligation_states: list[dict]) -> dict:
    """Obligation -> owner child -> that child's item state, copied verbatim. No obligation or parent is ever judged from it."""
    hier = _hierarchy(contract)
    state = {row["field_id"]: row for row in obligation_states}
    absent = [c["child_id"] for c in hier["children"] if c["child_id"] not in state]
    if absent:
        raise HierarchyRejected([f"no item state exists for child(ren) {absent}"])
    subordinates: dict[str, list[str]] = {}
    for c in hier["children"]:
        if c["parent"] != "R":
            subordinates.setdefault(c["parent"], []).append(c["child_id"])
    obligations = [
        {
            "obligation": o["id"],
            "kind": o["kind"],
            "text": o["text"],
            "owner_child": o["owner"],
            "representation": o["representation"],
            "owner_item_state": state[o["owner"]]["state"],
            "obligation_fulfilment": LABELS["obligation_fulfilment"],
        }
        for o in hier["obligations"]
    ]
    parents = [
        {
            "node": c["child_id"],
            "own_item_state": state[c["child_id"]]["state"],
            "subordinate_item_states": {s: state[s]["state"] for s in subordinates[c["child_id"]]},
            "parent_completeness": LABELS["parent_completeness"],
        }
        for c in hier["children"]
        if c["child_id"] in subordinates
    ]
    children = []
    for c in hier["children"]:
        row = state[c["child_id"]]
        reqs = c["requirements"]
        children.append(
            {
                "child_id": c["child_id"],
                "parent": c["parent"],
                "depth": c["depth"],
                "nesting": {k: c["nesting"].get(k) for k in ("kind", "clarification", "obligation")},
                "wording": c["wording"],
                "wording_sha256": c["wording_sha256"],
                "wording_provenance": c["wording_provenance"],
                "provenance_labels": list(c["provenance_labels"]),
                "execution_state": c["execution"]["state"],
                "approval_ref": c["execution"]["approval_ref"],
                "item_state": row["state"],
                "proposition_ids": list(row["proposition_ids"]),
                "mechanical_gaps": row.get("mechanical_gaps", 0),
                "owned_obligation_ids": list(c["owned_obligation_ids"]),
                "qualifications": [
                    {
                        "id": q["id"],
                        "text": q["text"],
                        "model_facing": q["model_facing"],
                        "excluded_reason": q["excluded_reason"],
                    }
                    for q in c["qualifications"]
                ],
                "active_constraints": [
                    {"id": r["id"], "text": r["text"], "model_facing": r["model_facing"]}
                    for r in reqs
                    if r["class"] == "active_constraint"
                ],
                "human_review_meanings": [
                    {
                        "id": r["id"],
                        "clarification": r["clarification"],
                        "text": r["text"],
                        "state": r["state"],
                        "decision": r["decision"],
                        "operationalized": False,
                        "assessed": False,
                        "note": HUMAN_REVIEW_NOTE,
                    }
                    for r in reqs
                    if r["class"] == "human_review_meaning"
                ],
                "superseded": [
                    {
                        "id": r["id"],
                        "state": r["state"],
                        "decision": (r["amendment"] or {}).get("decision"),
                        "asked_by_this_run": False,
                        "note": SUPERSEDED_NOTE,
                    }
                    for r in reqs
                    if r["class"] == "superseded_by_D10"
                ],
                "scope_carrier": copy.deepcopy(c["scope_carrier"]),
            }
        )
    return {
        "version": "hierarchy-rollup-v1",
        "note": ROLLUP_NOTE,
        "item_disclaimer": ITEM_DISCLAIMER,
        "human_review_statement": HUMAN_REVIEW_STATEMENT if any(c["human_review_meanings"] for c in children) else None,
        "labels": copy.deepcopy(LABELS),
        "closure_rule": hier["closure_rule"],
        "representation_accounted": {
            "accounted": sum(1 for o in obligations if o["representation"] == LABELS["representation"]),
            "of": len(obligations),
            "basis": REPRESENTATION_BASIS,
        },
        "obligations": obligations,
        "parents": parents,
        "children": children,
        "background": copy.deepcopy(hier["background"]),
        "d1": copy.deepcopy(hier["d1"]),
    }


