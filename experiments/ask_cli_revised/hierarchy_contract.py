def verify_run_contract(contract: dict, ledger: dict) -> dict:
    """Is the contract a run sealed still the approved hierarchy, and are the ledger's items exactly its children?"""
    problems: list[str] = []
    try:
        assert_executable(contract)
    except HierarchyRejected as exc:
        problems += exc.problems
    hier = contract.get("hierarchy") if isinstance(contract, dict) else None
    basis = "structural"
    if isinstance(hier, dict) and hier.get("children") and not problems:
        ids = [c["child_id"] for c in hier["children"]]
        state_ids = [s["field_id"] for s in ledger.get("obligation_states", [])]
        if state_ids != ids:
            problems.append(f"the ledger's items {state_ids} are not the approved children {ids}")
        if (hier.get("verification") or {}).get("pins") == "verified":
            basis = "pins"
            pins, pin_problems = _read_pins(FROZEN_PATH)
            problems += pin_problems
            if pins is not None and pins.get("model_facing_sha256") != model_facing_sha256(contract):
                problems.append("the model-facing text differs from the pinned model_facing_sha256")
    return {"ok": not problems, "problems": problems, "basis": basis}


def readiness_record(contract: dict) -> dict:
    hier = contract.get("hierarchy") or {}
    ready = hier.get("readiness") or {}
    return {
        "ok": ready.get("all_executable") is True,
        "all_executable": ready.get("all_executable"),
        "counts": ready.get("counts"),
        "verification": hier.get("verification"),
    }


def carriage_violations(contract: dict, calls: list[dict]) -> list[dict]:
    """Prompts actually sent that lost a child's exact item line or (for a scope-carrying child) its scope block."""
    subs = hierarchy_subquestions(contract)
    display = {s["subquestion_id"]: s["obligations"][0]["model_display"] for s in subs}
    text = {s["subquestion_id"]: s["text"] for s in subs}
    carriers = {c["child_id"]: c["scope_carrier"] for c in contract["hierarchy"]["children"] if c["scope_carrier"]}
    violations = []
    for index, row in enumerate(calls):
        task, prompt = row.get("task"), row.get("prompt_text") or ""
        fmt = _SUPERVISOR_ITEM_LINE.get(task)
        if fmt:
            for cid, shown in display.items():
                if fmt.format(id=cid, display=shown) not in prompt:
                    violations.append({"call": index, "task": task, "child": cid, "missing": "item line"})
        elif task in _WORKER_TASKS:
            child = next((cid for cid, t in text.items() if t in prompt), None)
            if child is None:
                violations.append(
                    {"call": index, "task": task, "child": None, "missing": "a child's exact retrieval text"}
                )
                continue
            if task == "select_evidence" and f"- {child}: {display[child]}" not in prompt:
                violations.append({"call": index, "task": task, "child": child, "missing": "item line"})
            if task == "recovery_query" and display[child] not in prompt:
                violations.append({"call": index, "task": task, "child": child, "missing": "item line"})
            if child in carriers and SCOPE_HEAD + carriers[child]["wording"] not in prompt:
                violations.append({"call": index, "task": task, "child": child, "missing": "scope block"})
    return violations


def _keys(value):
    if isinstance(value, dict):
        for k, v in value.items():
            yield str(k)
            yield from _keys(v)
    elif isinstance(value, list):
        for v in value:
            yield from _keys(v)


def rollup_violations(ledger: dict, answer: str) -> list[str]:
    """The roll-up may copy states and state the fixed labels; it may never carry or render a verdict."""
    roll = ledger.get("hierarchy")
    if not isinstance(roll, dict):
        return ["the sealed ledger carries no structural roll-up"]
    problems = []
    if roll.get("labels") != LABELS:
        problems.append("the roll-up labels differ from the fixed labels")
    states = set(LABELS["child_item_states"])
    for o in roll.get("obligations", []):
        if o.get("obligation_fulfilment") != LABELS["obligation_fulfilment"]:
            problems.append(
                f"obligation {o.get('obligation')} carries fulfilment value {o.get('obligation_fulfilment')!r}"
            )
        if o.get("owner_item_state") not in states:
            problems.append(f"obligation {o.get('obligation')} carries owner item state {o.get('owner_item_state')!r}")
    for p in roll.get("parents", []):
        if p.get("parent_completeness") != LABELS["parent_completeness"]:
            problems.append(f"parent {p.get('node')} carries completeness value {p.get('parent_completeness')!r}")
        if p.get("own_item_state") not in states or any(
            v not in states for v in (p.get("subordinate_item_states") or {}).values()
        ):
            problems.append(f"parent {p.get('node')} carries a state that is not an item state")
    problems += [
        f"the roll-up carries a verdict key {key!r}"
        for key in sorted({k for k in _keys(roll) if _VERDICT_KEY.match(k)})
    ]
    if _RECONCILIATION_HEADING not in (answer or ""):
        problems.append("the answer has no reconciliation section")
    else:
        section = answer.split(_RECONCILIATION_HEADING, 1)[1].split("\n## ", 1)[0]
        hits = sorted({m.lower() for m in _VERDICT.findall(section)})
        if hits:
            problems.append(f"the rendered reconciliation uses verdict word(s) {hits}")
    return problems


