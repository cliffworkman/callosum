def check_authorization(path, question: str) -> None:
    """The standing experiment gate (EXPERIMENT_GATE.md): a live run needs an authorization naming this exact request."""
    digest = sha256_text(question)
    if not path:
        raise AuthorizationRefused(
            "a live hierarchical run needs --experiment-authorization naming this experiment (see EXPERIMENT_GATE.md)"
        )
    try:
        auth = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise AuthorizationRefused(f"authorization file unreadable: {exc}") from exc
    complete = (
        isinstance(auth, dict)
        and auth.get("brief_confirmed") is True
        and all(str(auth.get(k) or "").strip() for k in ("experiment_id", "authorized_by", "authorized_at"))
        and digest in (auth.get("question_sha256s") or [])
    )
    if not complete:
        raise AuthorizationRefused(
            f"the authorization does not name this request ({digest[:12]}) with brief_confirmed=true, an experiment_id, authorized_by and authorized_at"
        )


