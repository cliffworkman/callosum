class HierarchyRejected(RuntimeError):
    """The hierarchy cannot run. ``problems`` names every reason found; nothing is ever partly accepted."""

    def __init__(self, problems):
        self.problems = [str(p) for p in problems]
        shown = "; ".join(self.problems[:5])
        more = f" (+{len(self.problems) - 5} more)" if len(self.problems) > 5 else ""
        super().__init__(f"hierarchy rejected: {shown}{more}")


class AuthorizationRefused(RuntimeError):
    """A live hierarchical run was started without an authorization naming this experiment."""


# ---- small pure helpers ---------------------------------------------------------------------------------------------


def sha256_text(text: str) -> str:
    return hashlib.sha256(str(text).encode("utf-8")).hexdigest()


def _sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _canonical(value) -> str:
    return json.dumps(value, sort_keys=True, ensure_ascii=False)


def provenance_tokens(text: str) -> list[str]:
    """Identifiers and labels that belong in the contract and report, never in a model's input."""
    return [m.group(0) for m in _PROVENANCE.finditer(str(text))]


def mentions_networks(text: str) -> bool:
    return bool(_NETWORKS.search(str(text)))


def _norm_tokens(text: str) -> set[str]:
    return set(re.sub(r"[^a-z0-9]+", " ", str(text).lower()).split())


# ---- model-facing text ----------------------------------------------------------------------------------------------


def model_constraints(child: dict) -> list[str]:
    """Exact approved constraint texts a model may see: eligible node qualifications first, then active requirement constraints."""
    return [q["text"] for q in child["qualifications"] if q["model_facing"]] + [
        r["text"] for r in child["requirements"] if r["model_facing"]
    ]


def model_facing_components(child: dict) -> list[str]:
    """Every scientific string a model sees for this child (excluding the fixed template words and the original request)."""
    parts = [child["wording"]]
    if child["scope_carrier"]:
        parts.append(child["scope_carrier"]["wording"])
    return parts + model_constraints(child)


def retrieval_text(child: dict, question: str) -> str:
    scope = f"{SCOPE_HEAD}{child['scope_carrier']['wording']}\n\n" if child["scope_carrier"] else ""
    return f"{FOCUS}{child['wording']}\n\n{scope}{CONTEXT}{question}"


def model_display(child: dict) -> str:
    out = child["wording"]
    if child["scope_carrier"]:
        out += DISPLAY_SCOPE.format(child["scope_carrier"]["wording"])
    items = model_constraints(child)
    if items:
        out += DISPLAY_CONSTRAINTS.format(" ".join(f"({i}) {t}" for i, t in enumerate(items, 1)))
    return out


def _obligation_hierarchy(child: dict) -> dict:
    keys = (
        "child_id",
        "parent",
        "depth",
        "nesting",
        "folded",
        "wording_sha256",
        "wording_provenance",
        "provenance_labels",
        "status",
        "execution",
        "approval",
        "qualifications",
        "requirements",
        "structural_requirements",
        "scope_carrier",
        "owned_obligation_ids",
    )  # the recorded prior wordings ("history") stay in the contract itself, not copied onto every item
    return copy.deepcopy({k: child[k] for k in keys})


def hierarchy_subquestions(contract: dict) -> list[dict]:
    """The subquestions the E2E consumes: one per approved child, same shape as ``request_subquestions``.

    Reads only the hierarchy. It never falls back to literal source units, whatever the contract might also carry.
    """
    hier = _hierarchy(contract)
    question = contract["original_question"]
    subquestions = []
    for child in hier["children"]:
        cid = child["child_id"]
        subquestions.append(
            {
                "subquestion_id": cid,
                "source_unit_id": cid,
                "child_id": cid,
                "question_hash": contract["question_hash"],
                "original_question": question,
                "text": retrieval_text(child, question),
                "retrieval_view_kind": "approved_child_with_scope_and_original_context",
                "obligations": [
                    {
                        "field_id": cid,
                        "note": child["wording"],
                        "source_unit_id": cid,
                        "coverage_basis": "approved_child",
                        "model_display": model_display(child),
                        "hierarchy": _obligation_hierarchy(child),
                    }
                ],
            }
        )
    return subquestions


def model_facing_sha256(contract: dict) -> str:
    """A hash over everything a model is shown about the request (the frozen model-facing contract of this arm)."""
    return sha256_text(
        _canonical(
            {
                "original_question": contract["original_question"],
                "subquestions": [
                    {
                        "subquestion_id": s["subquestion_id"],
                        "retrieval_text": s["text"],
                        "display": s["obligations"][0]["model_display"],
                    }
                    for s in hierarchy_subquestions(contract)
                ],
            }
        )
    )


_SEALED = ("inputs", "children", "obligations", "background", "folded", "requirement_table", "readiness")


def integrity_sha256(hier: dict) -> str:
    """A seal over the hierarchy as loaded: any later in-memory change to it is detectable."""
    return sha256_text(_canonical({k: hier.get(k) for k in _SEALED}))


def _hierarchy(contract) -> dict:
    if not isinstance(contract, dict) or contract.get("version") != HIER_VERSION:
        version = contract.get("version") if isinstance(contract, dict) else None
        raise HierarchyRejected([f"not a {HIER_VERSION} contract (version {version!r})"])
    hier = contract.get("hierarchy")
    if not isinstance(hier, dict) or not hier.get("children"):
        raise HierarchyRejected(["the contract carries no hierarchy"])
    return hier


# ---- reading the four inputs ----------------------------------------------------------------------------------------


def _resolve_paths(**given) -> dict[str, Path]:
    return {name: Path(given.get(name) or DEFAULT_PATHS[name]) for name in _INPUT_NAMES}


def _read_inputs(paths: dict[str, Path]):
    docs, shas, problems = {}, {}, []
    for name, path in paths.items():
        try:
            raw = Path(path).read_bytes()
            docs[name] = json.loads(raw.decode("utf-8"))
            shas[name] = _sha256_bytes(raw)
        except (OSError, ValueError) as exc:
            problems.append(f"{name}: artifact unreadable ({type(exc).__name__}: {exc})")
    return docs, shas, problems


def _code_shas() -> dict[str, str]:
    return {name: _sha256_bytes(Path(p).read_bytes()) for name, p in CODE_INPUTS.items()}


