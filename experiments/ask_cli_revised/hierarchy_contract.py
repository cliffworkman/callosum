def main(argv: list[str]) -> int:
    from experiments.ask_cli_revised.question import BENCHMARK_QUESTION

    command = argv[0] if argv else "verify"
    if command == "freeze":
        pins = freeze()
        print(f"wrote {FROZEN_PATH.name} (UNREVIEWED candidate) and {SHEET_PATH.name}")
        print(f"pins sha256: {pins_sha256(FROZEN_PATH)}")
        for key, value in pins["inputs"].items():
            print(f"  {key}: {value}")
        return 0
    if command == "verify":
        try:
            contract = load_contract(BENCHMARK_QUESTION)
        except HierarchyRejected as exc:
            print("HIERARCHY REJECTED:")
            for problem in exc.problems:
                print(f"  - {problem}")
            return 1
        v = contract["hierarchy"]["verification"]
        print(
            f"hierarchy intact: {len(contract['hierarchy']['children'])} executable children; pins {v['pins']}; review {v['review']}"
        )
        if v["review"] != "reviewed":
            print("PINS UNREVIEWED: a live run will refuse until a review record names the current pin file")
        return 0
    print("usage: freeze | verify")
    return 2


