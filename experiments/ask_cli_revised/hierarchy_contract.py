def _requirement_records(cid, node, req_rows, amendments, problems):
    records, structural = [], []
    for res in node.get("requirement_results", []):
        rid, state = res["id"], res["state"]
        row = req_rows.get(rid)
        if row is None:
            if not _STRUCTURAL_ID.match(rid):
                problems.append(
                    f"{cid}: requirement {rid!r} has no recorded row and is not a structural check (unclassified)"
                )
            elif state not in _STRUCTURAL_OK:
                problems.append(f"{cid}: structural requirement {rid!r} is not satisfied (state {state!r})")
            structural.append({"id": rid, "state": state})
            continue
        kind, text = row.get("kind"), row.get("text")
        amendment = None
        if kind == "constraint":
            cls = "active_constraint"
        elif kind == "scope_item":
            names_networks = mentions_networks(" ".join([rid, str(text), *map(str, row.get("phrases", []))]))
            cls = "superseded_by_D10" if names_networks else "human_review_meaning"
        elif kind == "qualifier_expression":
            cls = "human_review_meaning"
        else:
            problems.append(f"{cid}: requirement {rid!r} has unclassified kind {kind!r}")
            continue
        if cls == "superseded_by_D10":
            amendment = amendments.get(rid)
            if amendment is None or amendment.get("effect") != "optional_scope_expansion":
                problems.append(
                    f"{cid}: no D10 amendment (optional_scope_expansion) is recorded for {rid!r} in the closure decisions"
                )
            if state != "optional_by_amendment" or "D10" not in (res.get("amended_by") or []):
                problems.append(
                    f"{cid}: brain networks ({rid!r}) must stay optional_by_amendment under D10, found {state!r}"
                )
        elif state not in _REQUIREMENT_STATES[cls]:
            problems.append(f"{cid}: requirement {rid!r} has state {state!r}, not accepted for a {cls}")
        model_facing = (
            cls == "active_constraint" and not provenance_tokens(text or "") and not mentions_networks(text or "")
        )
        records.append(
            {
                "id": rid,
                "kind": kind,
                "text": text,
                "phrases": row.get("phrases"),
                "clarification": row.get("clarification"),
                "decision": row.get("decision"),
                "approved_by": row.get("approved_by"),
                "class": cls,
                "state": state,
                "amended_by": res.get("amended_by"),
                "amendment": (
                    {k: amendment.get(k) for k in ("decision", "effect", "approved_by", "note")} if amendment else None
                ),
                "model_facing": model_facing,
            }
        )
    return records, structural


def _qualification_records(cid, node, problems):
    out = []
    for q in node.get("qualifications", []):
        match = _QUAL_ID.match(str(q.get("id", "")))
        if not match or match.group(1) != cid:
            problems.append(
                f"{cid}: qualification id {q.get('id')!r} is not a recognized preserve/constraint/retained-scope id of this child"
            )
            continue
        kind, slug, text = match.group(2), match.group(3), q.get("text")
        if not text or not q.get("approved_by") or not q.get("decision"):
            problems.append(f"{cid}: qualification {q['id']!r} lacks its exact text, approver or decision")
            continue
        tokens = sorted(set(provenance_tokens(text)))
        reason = None
        if kind == "retained-scope":
            reason = "a provenance statement about the parent link; its scientific effect is the scope context carried from the parent"
        elif tokens:
            reason = f"the exact approved text contains provenance token(s) {tokens}; kept machine-side, never paraphrased for a model"
        elif mentions_networks(text):
            problems.append(f"{cid}: qualification {q['id']!r} mentions brain networks, which are optional under D10")
            reason = "mentions brain networks"
        out.append(
            {
                "id": q["id"],
                "kind": kind,
                "slug": slug,
                "text": text,
                "approved_by": q["approved_by"],
                "decision": q["decision"],
                "model_facing": reason is None,
                "excluded_reason": reason,
            }
        )
    return out


def _child_readiness(children_execution) -> dict:
    counts: dict[str, int] = {}
    for _, ex in children_execution:
        counts[ex["state"]] = counts.get(ex["state"], 0) + 1
    summary = execution.summarize([{"child_id": cid, "execution": ex} for cid, ex in children_execution])
    return {
        "all_executable": summary["all_executable"],
        "executable": summary["executable"],
        "requires_researcher_approval": summary["requires_researcher_approval"],
        "not_executable": summary["not_executable"],
        "counts": counts,
    }


def _build_unchecked(question, docs, paths, shas, problems):
    assembled, decisions, closure = docs["assembled"], docs["decisions"], docs["closure"]
    nodes = assembled["nodes"]
    recon = assembled["contract_reconciliation"]

    by_id: dict[str, dict] = {}
    for node in nodes:
        if node["child_id"] in by_id:
            problems.append(f"{node['child_id']}: appears twice among the children")
        by_id[node["child_id"]] = node

    approvals: list[dict] = []
    try:
        approvals = execution.load_approvals(paths["approvals"])
    except (ValueError, OSError) as exc:
        problems.append(f"approvals: {exc}")
    problems += [f"approvals: {p}" for p in execution.verify_approvals(approvals)]

    req_rows = {
        r["id"]: {**r, "clarification": ann["clarification"]}
        for ann in decisions.get("annotations", [])
        for r in ann.get("requirements", [])
    }
    amendments = {a["amends"]: a for ann in closure.get("annotations", []) for a in ann.get("amendments", [])}

    folded_map = {n["child_id"]: list(n["folded"]) for n in nodes if n.get("folded")}
    background = list(recon.get("background", []))
    for parent, folded in folded_map.items():
        for fid in folded:
            if fid in by_id:
                problems.append(f"{fid}: is recorded as folded into {parent} and must not also be a child")
    for b in background:
        if b["id"] in by_id:
            problems.append(f"{b['id']}: is background (never asked) and must not be a child")

    owned: dict[str, list[str]] = {cid: [] for cid in by_id}
    obligations = []
    for row in recon.get("preservation", []):
        if row["owner"] not in by_id:
            problems.append(
                f"obligation {row['obligation']} is owned by {row['owner']!r}, which is not among the children"
            )
        accounted = row["state"] in ("present", "explained_by_decision")
        if not accounted:
            problems.append(
                f"obligation {row['obligation']} is not accounted for in its owner's wording (state {row['state']!r})"
            )
        owned.setdefault(row["owner"], []).append(row["obligation"])
        obligations.append(
            {
                "id": row["obligation"],
                "kind": row["kind"],
                "text": row["text"],
                "owner": row["owner"],
                "representation": LABELS["representation"] if accounted else "not_accounted",
                "explained": row.get("explained"),
            }
        )
    if recon.get("unaccounted") != [] or recon.get("missing") != []:
        problems.append(
            f"contract reconciliation lists unaccounted {recon.get('unaccounted')} / missing {recon.get('missing')} obligations"
        )
    if recon.get("obligations_checked") != len(obligations):
        problems.append("contract reconciliation count does not match its obligation rows")
    if recon.get("plans_identical_to_frozen") is not True:
        problems.append("contract reconciliation says the plans differ from the frozen v6 plans")

    children, children_execution = [], []
    for node in nodes:
        cid = node["child_id"]
        wording = node.get("wording")
        ex = node.get("execution") or {}
        state = ex.get("state")
        if not isinstance(wording, str) or not wording.strip():
            problems.append(f"{cid}: has no exact wording")
            wording = str(wording or "")
        sha = sha256_text(wording)
        if ex.get("wording_sha256") != sha:
            problems.append(f"{cid}: the wording does not match the hash recorded in its execution record")
        if ex.get("executable") is not True or state not in execution.EXECUTABLE:
            problems.append(f"{cid}: not executable (execution state {state!r}); a status label never authorizes a run")
        status = node.get("status")
        if status in execution.HARD_STATUSES:
            problems.append(f"{cid}: has hard status {status!r}; an approval never overrides it")
        approval, expected_quals = None, []
        if state == execution.RESEARCHER_APPROVED:
            probe = {
                "child_id": cid,
                "kind": "researcher_supplied" if status == "researcher_supplied" else "anchor",
                "status": status,
                "question": wording,
            }
            again = execution.readiness(probe, approvals=approvals)
            if again["state"] != execution.RESEARCHER_APPROVED:
                problems.append(f"{cid}: no approval names this exact wording (recomputed state {again['state']!r})")
            else:
                approval = again.get("approval")
                expected_quals = again.get("qualifications", [])
                if node.get("approval") != approval:
                    problems.append(f"{cid}: the recorded approval differs from the approval file")
        else:
            if state not in (execution.RUNNABLE_BY_CONSTRUCTION, execution.RUNNABLE_ORIGINAL):
                pass  # already reported above as not executable
            elif status != "candidate" or node.get("flags"):
                problems.append(
                    f"{cid}: is runnable by construction only as a clean candidate; found status {status!r}, flags {node.get('flags')}"
                )
            if node.get("qualifications"):
                problems.append(f"{cid}: carries qualifications without an approval record")
        quals = _qualification_records(cid, node, problems)
        if state == execution.RESEARCHER_APPROVED and [(q["id"], q["text"]) for q in quals] != [
            (q["id"], q["text"]) for q in expected_quals
        ]:
            problems.append(f"{cid}: qualifications differ from the approval record")
        reqs, structural = _requirement_records(cid, node, req_rows, amendments, problems)

        parent, depth, nesting = node.get("parent"), node.get("depth"), node.get("nesting") or {}
        if parent == "R":
            if depth != 1 or nesting.get("kind") != "top_level":
                problems.append(f"{cid}: a top-level child must have depth 1 and top_level nesting")
        elif parent not in by_id:
            problems.append(f"{cid}: parent {parent!r} is not among the children")
        elif depth != by_id[parent].get("depth", 0) + 1:
            problems.append(f"{cid}: depth {depth} is inconsistent with parent {parent}")

        carrier = None
        retained = [q for q in quals if q["kind"] == "retained-scope"]
        if retained:
            if parent == "R" or nesting.get("kind") != "clarified_antecedent" or parent not in by_id:
                problems.append(
                    f"{cid}: a retained-scope qualification is recorded but the child has no clarified parent link"
                )
            else:
                parent_wording = by_id[parent]["wording"]
                if not _norm_tokens(retained[0]["slug"]) <= _norm_tokens(parent_wording):
                    problems.append(
                        f"{cid}: retained-scope {retained[0]['slug']!r} is not carried by the exact wording of parent {parent}"
                    )
                obligation_text = next((o["text"] for o in obligations if o["id"] == nesting.get("obligation")), None)
                carrier = {
                    "from": parent,
                    "via": nesting.get("clarification"),
                    "obligation": nesting.get("obligation"),
                    "obligation_text": obligation_text,
                    "wording": parent_wording,
                    "wording_sha256": sha256_text(parent_wording),
                }
        children.append(
            {
                "child_id": cid,
                "parent": parent,
                "depth": depth,
                "nesting": nesting,
                "folded": list(node.get("folded", [])),
                "wording": wording,
                "wording_sha256": sha,
                "provenance_labels": list(node.get("provenance", [])),
                "wording_provenance": (approval or {}).get("wording_provenance"),
                "status": status,
                "execution": {
                    "state": state,
                    "executable": ex.get("executable") is True,
                    "reasons": list(ex.get("reasons", [])),
                    "approval_ref": (approval or {}).get("approval_ref"),
                },
                "approval": approval,
                "qualifications": quals,
                "requirements": reqs,
                "structural_requirements": structural,
                "scope_carrier": carrier,
                "owned_obligation_ids": owned.get(cid, []),
                "history": copy.deepcopy(node.get("history", [])),
            }
        )
        children_execution.append((cid, {"state": state if state in _KNOWN_STATES else execution.NOT_EXECUTABLE}))

    readiness = _child_readiness(children_execution)
    if not readiness["all_executable"]:
        problems.append(
            f"not every child is executable: requires approval {readiness['requires_researcher_approval']}, not executable {readiness['not_executable']}"
        )

    pair = recon.get("c9_pairing")
    if pair is not None:
        absent = [m for m, ok in pair["members_present"].items() if not ok]
        if absent:
            problems.append(f"c9 pairing: member(s) {absent} are not present in the wording")
        if pair.get("asks_traits_again") is not False:
            problems.append("c9 pairing: the wording asks the traits again")
        node9 = by_id.get("c9")
        if node9 is None or node9.get("parent") != pair.get("nested_under"):
            problems.append(
                f"c9 pairing: nested under {pair.get('nested_under')!r} in the record but the node's parent is {(node9 or {}).get('parent')!r}"
            )
    scope = recon.get("c11_inherited_scope")
    if scope is not None and scope.get("retained_through_parent_link") is not True:
        problems.append("retained-scope: the closure record does not confirm c11 retains its parent's scope")

    for child in children:
        for text in model_facing_components(child):
            if provenance_tokens(text):
                problems.append(
                    f"{child['child_id']}: model-facing text carries provenance token(s) {sorted(set(provenance_tokens(text)))}"
                )
            if mentions_networks(text):
                problems.append(f"{child['child_id']}: model-facing text mentions brain networks (optional under D10)")

    requirement_table = {
        r["id"]: {"class": r["class"], "model_facing": r["model_facing"], "text_sha256": sha256_text(r["text"] or "")}
        for child in children
        for r in child["requirements"]
    }
    hier = {
        "question_key": "aib",
        "clarification_set": assembled.get("clarification_set"),
        "inputs": {f"{name}_sha256": shas[name] for name in _INPUT_NAMES},
        "children": children,
        "obligations": obligations,
        "background": background,
        "folded": folded_map,
        "requirement_table": requirement_table,
        "readiness": readiness,
        "closure_rule": CLOSURE_RULE,
        "labels": copy.deepcopy(LABELS),
        "d1": copy.deepcopy(D1_RECORD),
    }
    hier["integrity_sha256"] = integrity_sha256(hier)
    return {
        "version": HIER_VERSION,
        "original_question": question,
        "question_hash": sha256_text(question),
        "semantic_completeness": "not_certified",
        "hierarchy": hier,
    }


def _build(question, docs, paths, shas):
    problems: list[str] = []
    try:
        return _build_unchecked(question, docs, paths, shas, problems), problems
    except (KeyError, TypeError, AttributeError, IndexError, ValueError) as exc:
        problems.append(f"malformed artifact: {type(exc).__name__}: {exc}")
        return None, problems


def assert_executable(contract: dict) -> None:
    """Structural re-check of a loaded contract; ``execute()`` calls it before any stage runs.

    It recomputes everything that can be recomputed from the contract itself and never trusts the seal alone.
    """
    hier = _hierarchy(contract)
    problems = []
    if integrity_sha256(hier) != hier.get("integrity_sha256"):
        problems.append("the hierarchy no longer matches its seal (it was changed after loading)")
    if contract.get("question_hash") != sha256_text(contract.get("original_question", "")):
        problems.append("the question hash does not match the original question")
    ids = [c["child_id"] for c in hier["children"]]
    by_id = {c["child_id"]: c for c in hier["children"]}
    if len(set(ids)) != len(ids):
        problems.append("a child appears twice among the children")
    for child in hier["children"]:
        cid = child["child_id"]
        if sha256_text(child["wording"]) != child["wording_sha256"]:
            problems.append(f"{cid}: the wording does not match its recorded hash")
        ex = child["execution"]
        if ex.get("executable") is not True or ex.get("state") not in execution.EXECUTABLE:
            problems.append(f"{cid}: not executable (state {ex.get('state')!r})")
        parent = child["parent"]
        if parent != "R" and parent not in by_id:
            problems.append(f"{cid}: parent {parent!r} is not among the children")
        retained = [q for q in child["qualifications"] if q["kind"] == "retained-scope"]
        carrier = child["scope_carrier"]
        if retained and not carrier:
            problems.append(f"{cid}: a retained-scope qualification is recorded but no scope is carried")
        if carrier and not retained:
            problems.append(f"{cid}: carries a scope without a recorded retained-scope qualification")
        if carrier and carrier["wording"] != (by_id.get(carrier["from"]) or {}).get("wording"):
            problems.append(f"{cid}: the scope carried differs from the exact wording of {carrier['from']}")
        for q in child["qualifications"]:
            eligible = (
                q["kind"] != "retained-scope" and not provenance_tokens(q["text"]) and not mentions_networks(q["text"])
            )
            if q["model_facing"] and not eligible:
                problems.append(f"{cid}: qualification {q['id']!r} is model-facing but its exact text is not eligible")
        for r in child["requirements"]:
            if r["model_facing"] and r["class"] != "active_constraint":
                problems.append(
                    f"{cid}: requirement {r['id']!r} is model-facing, but no approved model-facing wording exists for it (D-1 = A)"
                )
        for text in model_facing_components(child):
            if provenance_tokens(text):
                problems.append(
                    f"{cid}: model-facing text carries provenance token(s) {sorted(set(provenance_tokens(text)))}"
                )
            if mentions_networks(text):
                problems.append(f"{cid}: model-facing text mentions brain networks (optional under D10)")
    for o in hier["obligations"]:
        if o["owner"] not in by_id:
            problems.append(f"obligation {o['id']} is owned by {o['owner']!r}, which is not among the children")
    recomputed = _child_readiness(
        [
            (
                c["child_id"],
                {
                    "state": c["execution"]["state"]
                    if c["execution"]["state"] in _KNOWN_STATES
                    else execution.NOT_EXECUTABLE
                },
            )
            for c in hier["children"]
        ]
    )
    if (
        recomputed["all_executable"] != (hier.get("readiness") or {}).get("all_executable")
        or not recomputed["all_executable"]
    ):
        problems.append(
            f"readiness: recomputed all_executable={recomputed['all_executable']}, recorded {(hier.get('readiness') or {}).get('all_executable')}"
        )
    if problems:
        raise HierarchyRejected(problems)


# ---- pins and review ------------------------------------------------------------------------------------------------


def pins_sha256(path) -> str:
    return _sha256_bytes(Path(path).read_bytes())


def _obligations_digest(hier: dict) -> dict:
    rows = sorted((o["id"], o["owner"]) for o in hier["obligations"])
    return {"count": len(rows), "ids_sha256": sha256_text(_canonical(rows))}


def build_pins(contract: dict, code_shas: dict) -> dict:
    hier = contract["hierarchy"]
    return {
        "version": PINS_VERSION,
        "status": (
            "UNREVIEWED_CANDIDATE: generated by hierarchy_contract freeze; not reviewed or approved by anyone. "
            "A live run requires hierarchy_contract.review.json naming this file's sha256."
        ),
        "question_key": hier["question_key"],
        "question_sha256": contract["question_hash"],
        "inputs": dict(hier["inputs"]),
        "code_inputs": dict(code_shas),
        "children": [
            {
                "child_id": c["child_id"],
                "parent": c["parent"],
                "depth": c["depth"],
                "wording_sha256": c["wording_sha256"],
                "execution_state": c["execution"]["state"],
                "wording_provenance": c["wording_provenance"],
                "approval_ref": c["execution"]["approval_ref"],
                "qualification_ids": [q["id"] for q in c["qualifications"]],
            }
            for c in hier["children"]
        ],
        "folded": hier["folded"],
        "obligations": _obligations_digest(hier),
        "requirements": hier["requirement_table"],
        "d1": hier["d1"],
        "model_facing_sha256": model_facing_sha256(contract),
    }


def _read_pins(path):
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return None, [f"pins: unreadable ({type(exc).__name__}: {exc})"]
    if not isinstance(doc, dict) or doc.get("version") != PINS_VERSION:
        return None, [f"pins: unsupported pin file (expected version {PINS_VERSION})"]
    return doc, []


def _check_pins(contract, code_shas, pins) -> list[str]:
    now = build_pins(contract, code_shas)
    problems = []
    if pins.get("question_sha256") != now["question_sha256"]:
        problems.append("pin drift: the question sha256 differs from the pinned question")
    for key in sorted(set(now["inputs"]) | set(pins.get("inputs", {}))):
        if now["inputs"].get(key) != pins.get("inputs", {}).get(key):
            problems.append(
                f"pin drift: {key} is {str(now['inputs'].get(key))[:12]}, pinned {str(pins.get('inputs', {}).get(key))[:12]}"
            )
    for key in sorted(set(now["code_inputs"]) | set(pins.get("code_inputs", {}))):
        if now["code_inputs"].get(key) != pins.get("code_inputs", {}).get(key):
            problems.append(f"pin drift: code input {key} changed since the pins were generated")
    pinned = {c["child_id"]: c for c in pins.get("children", [])}
    live = {c["child_id"]: c for c in now["children"]}
    if list(pinned) != list(live):
        problems.append(f"pin drift: children {list(live)} differ from pinned {list(pinned)}")
    for cid in live:
        if cid in pinned and pinned[cid] != live[cid]:
            fields = sorted(k for k in live[cid] if pinned[cid].get(k) != live[cid][k])
            problems.append(f"pin drift: child {cid} differs from its pin in {fields}")
    for key in ("folded", "obligations", "model_facing_sha256"):
        if pins.get(key) != now[key]:
            problems.append(f"pin drift: {key} differs from the pins")
    for rid, meta in sorted((pins.get("requirements") or {}).items()):
        if meta.get("model_facing") and meta.get("class") != "active_constraint":
            problems.append(
                f"pins make requirement {rid} model-facing, but no approved model-facing wording exists for it (D-1 = A)"
            )
    if pins.get("requirements") != now["requirements"]:
        problems.append("pin drift: the requirement classification table differs from the pins")
    return problems


def check_review(pins_path, review_path) -> tuple[str, list[str]]:
    """``("reviewed", [])`` only when a person's review record names the current pin file; otherwise ``("unreviewed", reasons)``."""
    try:
        review = json.loads(Path(review_path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        return "unreviewed", [
            f"review: no review record at {Path(review_path).name}; a live run needs an explicit review of these exact pins"
        ]
    except (OSError, ValueError) as exc:
        return "unreviewed", [f"review: record unreadable ({type(exc).__name__}: {exc})"]
    problems = []
    for field in ("reviewed_by", "reviewed_at", "pins_sha256"):
        if not isinstance(review.get(field), str) or not review[field].strip():
            problems.append(f"review: {field} is missing")
    if review.get("pins_sha256") != pins_sha256(pins_path):
        problems.append("review: pins_sha256 does not match the current pin file (the pins changed after the review)")
    pins, _ = _read_pins(pins_path)
    if pins is not None and review.get("inputs_sha256") != pins.get("inputs"):
        problems.append("review: inputs_sha256 does not match the pinned inputs")
    return ("reviewed", []) if not problems else ("unreviewed", problems)


# ---- loading --------------------------------------------------------------------------------------------------------

_DEFAULT = object()


def load_contract(
    question: str,
    *,
    assembled=None,
    approvals=None,
    decisions=None,
    closure=None,
    pins=_DEFAULT,
    review=None,
    require_review: bool = False,
) -> dict:
    """Verify the hierarchy and build its contract, or raise ``HierarchyRejected`` naming every problem.

    ``pins=None`` runs the structural checks only (tests). A live run passes ``require_review=True``: it refuses
    unless a person's review record names the current pin file.
    """
    if not isinstance(question, str) or not question.strip():
        raise HierarchyRejected(["a nonempty original question is required"])
    paths = _resolve_paths(assembled=assembled, approvals=approvals, decisions=decisions, closure=closure)
    pins_path = FROZEN_PATH if pins is _DEFAULT else pins
    review_path = Path(review) if review else REVIEW_PATH
    docs, shas, problems = _read_inputs(paths)
    if problems:
        raise HierarchyRejected(problems)
    contract, built = _build(question, docs, paths, shas)
    problems += built
    verification = {"pins": "not_checked", "review": "not_checked"}
    if pins_path is None:
        if require_review:
            problems.append("a live run requires the pin file; structural-only loading is for tests")
    elif contract is not None:
        pin_doc, pin_problems = _read_pins(pins_path)
        problems += pin_problems
        if pin_doc is not None:
            problems += _check_pins(contract, _code_shas(), pin_doc)
        verification["pins"] = "verified" if not problems else "failed"
        state, review_problems = check_review(pins_path, review_path)
        verification["review"] = state
        if require_review:
            problems += review_problems
    if problems or contract is None:
        raise HierarchyRejected(problems)
    contract["hierarchy"]["verification"] = verification
    return contract


def load_contract_for_live(question: str, *, review=None) -> dict:
    """The loader a live run uses: pins verified AND a person's review record naming the current pins."""
    return load_contract(question, require_review=True, review=review)


def load_contract_for_preflight(question: str) -> dict:
    """The loader ``--preflight-only`` uses: pins verified; an unreviewed pin file is reported, not refused."""
    return load_contract(question)


