def preflight_report(contract: dict) -> str:
    """Readiness and exactly what the models would be shown; produced with no side effect of any kind."""
    hier = _hierarchy(contract)
    v = hier.get("verification", {})
    lines = [
        "HIERARCHY PREFLIGHT (no model, library, database, output directory or network was touched)",
        "",
        f"contract {contract['version']}; question sha256 {contract['question_hash']}",
        f"pins: {v.get('pins')}; review: {v.get('review')}; model-facing sha256 {model_facing_sha256(contract)}",
    ]
    if v.get("review") != "reviewed":
        lines.append(
            "PINS UNREVIEWED: a live run refuses until a person records hierarchy_contract.review.json naming the current pin file "
            "(see HIERARCHY_FREEZE_REVIEW.md)"
        )
    lines += ["", f"children ({len(hier['children'])}; all executable: {hier['readiness']['all_executable']}):"]
    for c in hier["children"]:
        lines.append(
            f"  {c['child_id']}  parent={c['parent']}  {c['execution']['state']}  "
            f"provenance={c['wording_provenance'] or '(none recorded)'}  approval={c['execution']['approval_ref'] or '-'}"
        )
    lines += [
        "",
        "what the models are shown (retrieval text before the shared original-request context, then the item line):",
    ]
    for s in hierarchy_subquestions(contract):
        lines += [
            "",
            s["text"].split(CONTEXT)[0].rstrip(),
            f"- {s['obligations'][0]['field_id']}: {s['obligations'][0]['model_display']}",
        ]
    lines += [
        "",
        "labels used by every surface:",
        f"  representation: {LABELS['representation']}",
        f"  child-level responsiveness: {' | '.join(LABELS['child_item_states'])}",
        f"  obligation fulfilment: {LABELS['obligation_fulfilment']}",
        f"  parent answer completeness: {LABELS['parent_completeness']}",
    ]
    return "\n".join(lines)


