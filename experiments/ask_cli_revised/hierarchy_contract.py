def freeze(*, paths=None, pins_path=FROZEN_PATH, sheet_path=SHEET_PATH, question=None) -> dict:
    """Write the unreviewed pin candidate and its review sheet. It never writes a review record."""
    if question is None:
        from experiments.ask_cli_revised.question import BENCHMARK_QUESTION as question
    resolved = _resolve_paths(**(paths or {}))
    docs, shas, problems = _read_inputs(resolved)
    if problems:
        raise HierarchyRejected(problems)
    contract, built = _build(question, docs, resolved, shas)
    if built or contract is None:
        raise HierarchyRejected(built or ["the hierarchy could not be built"])
    code_shas = _code_shas()
    pins = build_pins(contract, code_shas)
    Path(pins_path).write_text(json.dumps(pins, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    Path(sheet_path).write_text(
        review_sheet(contract, pins, resolved, shas, code_shas, pins_sha256(pins_path)), encoding="utf-8", newline="\n"
    )
    return pins


