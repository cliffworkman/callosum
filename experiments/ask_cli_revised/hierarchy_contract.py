"""Transport of the closed q_aib v8 hierarchy into the experimental Ask E2E, at the existing request boundary.

The E2E takes a request contract and turns it into subquestions, each with one obligation. This module loads the
approved v8 hierarchy (11 executable children), verifies it, and emits a ``hierarchical-request-v1`` contract whose
subquestions have exactly that shape, so retrieval, evidence selection, R/C/P, sealing and rendering keep their code.
It is pure: no model, no network, no database, no library access.

What travels, and where:

* model-facing (retrieval text, item lines shown to W/R/C/P): the child's exact wording; for a child whose recorded
  qualifications include a ``retained-scope`` entry (c11) the parent's exact wording as scope context; and exact
  approved constraint texts under the neutral heading "Constraints for interpreting this question";
* machine-readable contract, sealed ledger and researcher-facing report only: approval refs, hashes, RC/CD/D/M
  identifiers, provenance labels, requirement records, human-review meanings, and the D10 record for brain networks.

Decision D-1 = A (Cliff): the non-network D4 human-review meanings (behavior measures, implicit/explicit attitude
measures, documented nature or direction where supported) are recorded and reported but are NOT model-facing, NOT
operationalized and NOT assessed by this run. The active no-presupposition constraint (RC-8/RC-9) IS model-facing.
Networks stay optional (D10) and are never shown to a model.

Trust limits, stated plainly: ``runnable_by_construction`` children (c1, c2, c3, c8, c10) cannot be re-derived here;
their recorded state is protected by file and per-child hashes, and the derivation stays covered by the engine's own
tests. The pin file is generated by this same code, so it is an UNREVIEWED candidate until a person reads the freeze
review sheet, recomputes the input hashes independently, and records a review that names the pin file's sha256.

Lineage: the scientific request, the scope decisions (D1-D10), the clarification approvals (RC-1..RC-10) and the
closure dispositions (CD-1..CD-5) are Cliff's; existing attributions in the closure records stand. This adapter's
architecture and implementation are Claude's, authorized by Cliff's requirements; it implements no scholarly method.

    python -m experiments.ask_cli_revised.hierarchy_contract freeze | verify
"""

