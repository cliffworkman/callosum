def _earlier_recorded_hashes(assembled_path: Path) -> dict[str, str]:
    """Approval hashes printed in the closure pass's own CLOSURE_DECISIONS.md, for an independent cross-check."""
    path = Path(assembled_path).with_name("CLOSURE_DECISIONS.md")
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return {}
    return {m.group(1): m.group(2) for m in re.finditer(r"^\|\s*(c\d+)\s*\|.*?`([0-9a-f]{64})`\s*\|\s*$", text, re.M)}


